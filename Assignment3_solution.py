#Q5: Write a program that uses any loop (while or for) that calculates the total of the following series of numbers:
#         1/30 + 2/29 + 3/28 ............. + 30/1

from fractions import Fraction

def calculate_series():
    total_sum = Fraction(0, 1)

    # Numerator goes from 1 to 30
    for i in range(1, 31):
        numerator = i
        denominator = 31 - i
        term = Fraction(numerator, denominator)
        total_sum += term

    # Output both formats
    print(f"Result as a Fraction: {total_sum}")
    print(f"Result in Decimal Points: {float(total_sum):.4f}")

calculate_series()

